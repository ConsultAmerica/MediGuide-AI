"""Assemble the API as a self-contained Vercel project in .vercel-api/.

The repository root also holds the Next.js frontend, the legacy Gradio app
and the full (torch/whisper) requirements, none of which belong in the API
function. This copies only what the API needs and adds Vercel's
configuration, so the folder can be deployed with `vercel deploy`.

    python scripts/build_vercel_api.py
    cd .vercel-api && vercel deploy --prod
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / ".vercel-api"

COPY = ["api.py", "alembic.ini", "src", "migrations", "data/knowledge", "data/samples"]
IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc", ".pytest_cache")

# Vercel's zero-config FastAPI entrypoint. Function filesystems are read-only
# apart from /tmp, and each request may run on a fresh instance, so working
# folders live in /tmp and record folders are mirrored in private Vercel
# Blob storage (src/shared/file_store.py). Project environment variables
# still win over these defaults.
ENTRYPOINT = '''"""Vercel entrypoint (generated by scripts/build_vercel_api.py)."""

import os

for _key, _value in {
    "MEDIGUIDE_FILE_STORE": "vercel-blob",
    "DOC_INTEL_TEMP_DIR": "/tmp/mediguide/documents",
    "IMAGING_TEMP_DIR": "/tmp/mediguide/imaging",
    "MED_WORKSPACE_TEMP_DIR": "/tmp/mediguide/medications",
    "SPEECH_OUTPUT_DIR": "/tmp/mediguide/speech",
    "VECTOR_STORE_DIR": "/tmp/mediguide/vector_store",
}.items():
    os.environ.setdefault(_key, _value)

from api import app  # noqa: E402,F401
'''

VERCEL_JSON = {
    "$schema": "https://openapi.vercel.sh/vercel.json",
    "functions": {"app.py": {"maxDuration": 60}},
}


def main() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir()
    for item in COPY:
        source = ROOT / item
        target = OUT / item
        target.parent.mkdir(parents=True, exist_ok=True)
        if source.is_dir():
            shutil.copytree(source, target, ignore=IGNORE)
        else:
            shutil.copy2(source, target)
    shutil.copy2(ROOT / "requirements-vercel.txt", OUT / "requirements.txt")
    (OUT / "app.py").write_text(ENTRYPOINT, encoding="utf-8")
    (OUT / "vercel.json").write_text(json.dumps(VERCEL_JSON, indent=2) + "\n", encoding="utf-8")
    (OUT / ".python-version").write_text("3.12\n", encoding="utf-8")
    size = sum(f.stat().st_size for f in OUT.rglob("*") if f.is_file())
    print(f"Built {OUT.relative_to(ROOT)} ({size / 1_048_576:.1f} MB of source)")


if __name__ == "__main__":
    main()
